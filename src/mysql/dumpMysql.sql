# criar tabelas do schema suppa

USE suppa;
 
 DROP TABLE if EXISTS CATEGORIAS;
CREATE TABLE CATEGORIAS (

	ID_CATEGORIA INTEGER PRIMARY KEY AUTO_INCREMENT,
    DESCRICAO_CATEGORIA VARCHAR(100)
);

DROP TABLE IF EXISTS SUBCATEGORIAS;
CREATE TABLE SUBCATEGORIAS (
	ID_SUBCATEGORIA INTEGER PRIMARY KEY AUTO_INCREMENT,
    DESCRICAO_SUBCATEGORIA VARCHAR(100)
);


DROP TABLE IF EXISTS UNIDADE_MEDIDAS;
CREATE TABLE UNIDADE_MEDIDAS (
	ID_UNIDADE_MEDIDA integer primary key AUTO_INCREMENT,
    SIGLA_UNIDADE char(5),
	DESCRICAO_UNIDADE VARCHAR(50)
);

DROP TABLE IF EXISTS FORNECEDORES;
CREATE TABLE FORNECEDORES (
	ID_FORNECEDOR INTEGER PRIMARY KEY AUTO_INCREMENT,
    NOME_FORNECEDOR VARCHAR(100),
    CONTATO_FORNECEDOR VARCHAR(50),
    CNPJ_FORNECEDOR VARCHAR(20),
    END_FORNECEDOR VARCHAR(100),
    SITE_FORNECEDOR VARCHAR(200)
);

DROP TABLE IF EXISTS SITUACOES;
CREATE TABLE SITUACOES (
	ID_SITUACAO INTEGER PRIMARY KEY AUTO_INCREMENT,
    NOME_SITUACAO VARCHAR(20)
);

 DROP TABLE IF EXISTS PRODUTOS;
 CREATE TABLE PRODUTOS (
	ID_PRODUTO INTEGER PRIMARY KEY AUTO_INCREMENT ,
    COD_BARRAS VARCHAR(50) UNIQUE,  -- Não pode ter duas iguais
    NOME_PRODUTO VARCHAR(200)  NOT NULL ,
    FOTO_PRODUTO VARCHAR (255), -- guardar caminho da foto
    VALOR_UNITARIO DECIMAL(18,2),
    ID_CATEGORIA INTEGER ,
    ID_SUBCATEGORIA INTEGER,
    QTD_PRODUTO_ESTOQUE INTEGER,
    ID_UNIDADE_MEDIDA INTEGER,
    DIAS_ANTES_VALIDADE_ALERTA INTEGER,
    
    CONSTRAINT FK_CATEGORIA
    FOREIGN KEY (ID_CATEGORIA)
    REFERENCES CATEGORIAS(ID_CATEGORIA),
    
    CONSTRAINT FK_SUBCATEGORIA
    FOREIGN KEY (ID_SUBCATEGORIA)
    REFERENCES SUBCATEGORIAS(ID_SUBCATEGORIA),
    
    CONSTRAINT FK_UNIDADE_MEDIDA
    FOREIGN KEY (ID_UNIDADE_MEDIDA)
    REFERENCES UNIDADE_MEDIDAS(ID_UNIDADE_MEDIDA)
    );
    
